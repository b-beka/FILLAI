// Иконка сферы или подтемы; неизвестное имя рисует book. Обводка как у Icon в Icons.tsx
// Файл .ts, поэтому без JSX
export function TopicIcon({ name, size, strokeWidth = 1.5 }: { name?: string | null; size: string; strokeWidth?: number }): ReactElement {
  const Cmp = (name && ICONS[name]) || ICONS.book;
  // Декоративная иконка; ключ задан присваиванием, чтобы тест синхронизации не принял его за имя иконки
  const props: LucideProps = { size, strokeWidth };
  props['aria-hidden'] = true;
  return createElement(Cmp, props);
}
